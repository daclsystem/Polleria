function money(items: { qty: number; price: number }[], discount = 0) {
  const gross = items.reduce((s, i) => s + i.qty * i.price, 0)
  const total = Math.max(0, Math.round((gross - discount) * 100) / 100)
  const subtotal = Math.round((total / 1.18) * 100) / 100
  const igv = Math.round((total - subtotal) * 100) / 100
  return { subtotal, igv, total, discount }
}

function order(
  partial: Omit<Order, 'subtotal' | 'igv' | 'total' | 'discount'> & { discount?: number },
): Order {
  const m = money(partial.items, partial.discount ?? 0)
  return { ...partial, ...m }
}

